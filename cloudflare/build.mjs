// Bundles the dashboard frontend (shared with the Python version) into the Worker script as strings,
// so deploys need no separate static-asset upload.
import { readFileSync, writeFileSync } from "node:fs";
const files = {
  "/": ["index.html", "text/html; charset=utf-8"],
  "/static/app.js": ["app.js", "text/javascript; charset=utf-8"],
  "/static/styles.css": ["styles.css", "text/css; charset=utf-8"],
};
const out = Object.fromEntries(Object.entries(files).map(([path, [file, type]]) =>
  [path, { type, body: readFileSync(`../dashboard/static/${file}`, "utf8") }]));
writeFileSync("src/assets.generated.js",
  "// Generated by build.mjs from dashboard/static. Do not edit.\nexport default " + JSON.stringify(out) + ";\n");
console.log("Bundled", Object.keys(out).length, "frontend files into src/assets.generated.js");
