-- Defence in depth: RLS on, no policies, so anon/authenticated roles can read or write nothing.
do $$ declare t text; begin
  for t in select tablename from pg_tables where schemaname = 'shakhira' loop
    execute format('alter table shakhira.%I enable row level security', t);
    execute format('revoke all on shakhira.%I from public, anon, authenticated', t);
  end loop;
end $$;

-- The ONE way the server reaches these tables: a single parameter-free statement, already safely quoted by the
-- server (cloudflare/src/pg.js). Callable only with the service-role/secret key (never sent to browsers).
create or replace function public.shakhira_exec(q text, mode text default 'all')
returns jsonb language plpgsql security definer set search_path = shakhira, pg_temp as $$
declare res jsonb;
begin
  if q ~ ';' then raise exception 'single statements only'; end if;
  if q !~* '^\s*(select|insert|update|delete|with)\s' then raise exception 'statement type not allowed'; end if;
  if q ~* '\m(pg_|information_schema|auth\.|storage\.|public\.|drop|alter|create|grant|revoke|truncate|copy|execute|set_config)' then
    raise exception 'forbidden identifier';
  end if;
  if mode = 'all' then
    execute format('select coalesce(jsonb_agg(t), ''[]''::jsonb) from (%s) t', q) into res;
  else
    execute format('with t as (%s) select jsonb_build_object(''rows'', coalesce(jsonb_agg(t), ''[]''::jsonb), ''changes'', count(*)) from t', q) into res;
  end if;
  return res;
end $$;
revoke all on function public.shakhira_exec(text, text) from public, anon, authenticated;
grant execute on function public.shakhira_exec(text, text) to service_role;
