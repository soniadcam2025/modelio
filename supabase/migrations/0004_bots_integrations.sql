-- Same as cloudflare/migrations/0005_bots_integrations.sql. Ciphertext only; the key is a Worker secret.
create table if not exists shakhira.bots (id bigint generated by default as identity primary key, bot_user_id bigint not null unique,
  username text not null, name text not null default '', token_cipher text not null default '', token_hint text not null default '',
  status text not null default 'active', is_primary integer not null default 0, automation_enabled integer not null default 0,
  permissions_json text not null default '{}', webhook_json text not null default '{}', last_check_at bigint, last_check_ok integer,
  last_error text not null default '', created_at bigint not null, updated_at bigint not null);
create table if not exists shakhira.bot_channels (id bigint generated by default as identity primary key, bot_id bigint not null,
  chat_id text not null unique, title text not null default '', kind text not null default 'channel', created_at bigint not null);
create table if not exists shakhira.integration_secrets (name text primary key, cipher text not null, hint_json text not null default '{}',
  last_check_at bigint, last_check_ok integer, last_error text not null default '', updated_at bigint not null);
alter table shakhira.content_items add column if not exists bot_id bigint;
alter table shakhira.audit_log add column if not exists bot_id bigint;
create index if not exists audit_bot on shakhira.audit_log (bot_id, id);
alter table shakhira.bots enable row level security;
alter table shakhira.bot_channels enable row level security;
alter table shakhira.integration_secrets enable row level security;
revoke all on shakhira.bots, shakhira.bot_channels, shakhira.integration_secrets from public, anon, authenticated;
grant select, insert, update, delete on shakhira.bots, shakhira.bot_channels, shakhira.integration_secrets to shakhira_app;
grant usage, select on all sequences in schema shakhira to shakhira_app;
